export const getModelsForMake = (makeName) => {
  if (!makeName) return [];
  const normalizedKey = Object.keys(PAKISTANI_CAR_MAKES).find(
    (key) => key.toLowerCase() === makeName.trim().toLowerCase()
  );
  return normalizedKey ? PAKISTANI_CAR_MAKES[normalizedKey] : [];
};
